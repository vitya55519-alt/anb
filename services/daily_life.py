def _slot(hour: int) -> str:
    for start, name in _SLOTS:
        if hour >= start:
            return name
    return 'night'


def her_moment(character_id: str | None, local: dt.datetime) -> str:
    """Where she is right now, for the prompt. Empty for girls without a routine."""
    routine = ROUTINES.get(character_id or '')
    if not routine:
        return ''
    variants = routine[_slot(local.hour)]
    doing = variants[local.toordinal() % len(variants)]
    weekday = _WEEKDAYS[local.weekday()]
    return (
        f'ТВОЙ ДЕНЬ СЕЙЧАС (у тебя тоже {local.strftime("%H:%M")}, {weekday}): {doing}. '
        'Пиши изнутри этого момента, но не начинай каждое сообщение с его описания: '
        'упоминай, когда к месту. Занятие меняй только если прошло время или он предложил другое.'
    )
