def check_achievements(user, character_state) -> list:
    """Check which achievements user has unlocked. Returns list of achievement keys."""
    unlocked = []
    for key, ach in ACHIEVEMENTS.items():
        try:
            if ach['check'](user, character_state):
                unlocked.append(key)
        except Exception:
            pass
    return unlocked


