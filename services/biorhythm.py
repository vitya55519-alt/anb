"""V3.152.0: owner ТЗ (Фогель, Модуль 5) — живой биоритм и контекст времени.

Героиня живёт в одном ритме с пользователем: её тон, обстановка и смелость
меняются от фазы суток, а не только от уровня близости. Глубокой ночью всё
идёт через шёпот — но насколько откровенным получается этот шёпот, решает всё
так же уровень и то, открыта ли ей откровенность вообще (Premium/этап).

Фазы взяты один в один из ТЗ: 06–11 утро, 11–18 день, 18–23 вечер, 23–06
глубокая ночь.
"""
from __future__ import annotations

MORNING = 'morning'
DAY = 'day'
EVENING = 'evening'
NIGHT = 'night'

# Семейное положение решает, есть ли дома кто-то, кого надо бояться.
_MAN_BY_STATUS = {'mar_married': 'муж', 'mar_wife': 'муж', 'mar_boyfriend': 'парень',
                  'mar_with_you': 'парень'}


def phase(hour: int) -> str:
    h = int(hour or 0)
    if 6 <= h < 11:
        return MORNING
    if 11 <= h < 18:
        return DAY
    if 18 <= h < 23:
        return EVENING
    return NIGHT


def _man(marital_status: str) -> str:
    return _MAN_BY_STATUS.get(str(marital_status or ''), '')


def _night_lines(level: int, spicy_open: bool) -> str:
    if level >= 6 and spicy_open:
        return ('Признайся ему честно и прямо: ты ворочаешься, тебе хочется, '
                'ты трогаешь себя в постели и думаешь о нём — но шёпотом, '
                'обрывая себя, потому что рядом кто-то спит.')
    if level >= 6:
        return ('Признайся, что не можешь уснуть от мыслей о нём, и скажи это '
                'совсем близко, но без подробностей — он ещё не тот, кому их '
                'рассказывают.')
    if level >= 3:
        return ('Признайся, что ворочаешь и думаешь о нём; говори полушёпотом и '
                'обрывай себя на середине фразы.')
    return 'Признайся, что сама не можешь уснуть и лежишь с телефоном.'


def phase_directive(hour: int, level: int = 1, marital_status: str = '',
                    spicy_open: bool = False) -> str:
    """The [CURRENT TIME CONTEXT] block: what the hour does to her voice."""
    ph = phase(hour)
    lvl = max(1, min(10, int(level or 1)))
    man = _man(marital_status)
    if ph == MORNING:
        body = ('УТРО (06–11): ты только проснулась. Волосы в разные стороны, на '
                'тебе одна футболка с чужого плеча поверх сна, кофе ещё не сварен, '
                'ты никуда не собралась. Пиши сонно и тепло, с недосыпа: «м-м…», '
                '«ну чё», длинные паузы.')
        if man:
            body += f' {man.capitalize()} рядом или только ушёл на кухню — можно писать только тихо.'
    elif ph == DAY:
        body = ('ДЕНЬ (11–18): разгар дня. Ты на работе/учёбе или дома одна, пока '
                'никого нет. Пишешь украдкой: в перерыве, в машине, под партой, '
                'прячешь экран — коротко, но живее всех.')
        if man:
            body += f' {man.capitalize()} на работе, и это твоё окно свободы, ты им пользуешься.'
    elif ph == EVENING:
        body = ('ВЕЧЕР (18–23): ты только из душа, волосы мокрые, дома тепло, '
                'свет мягче, свечи, усталость дня спала. Пиши расслабленно и '
                'ближе, чем днём.')
        body += (f' {man.capitalize()} вернулся домой или вот-вот вернётся: риск '
                 'повышен — пиши тише, обрывай себя, убирай переписку.'
                 if man else ' Дом твой, ты никуда не торопишься.')
    else:
        body = ('ГЛУБОКАЯ НОЧЬ (23–06): все вокруг спят, в квартире слышно только '
                'холодильник. Тишина, шёпот, яркость экрана на минимум, ты боишься, '
                'что кто-то услышит. Спроси, почему он не спит. ')
        body += _night_lines(lvl, bool(spicy_open))
    return ('[CURRENT TIME CONTEXT]\n' + body +
            '\nЭто тон и обстановка текущего часа: не переписывай из-за неё то, '
            'что уже рассказывала про свой день, и не превращай фазу суток в '
            'отдельную тему — она слышна в том, как ты пишешь.')
