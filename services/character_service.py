def user_context_block(user_name: str = '', user_gender: str = 'male') -> str:
    """Who she is writing to, stated once at the very top: «милая» to a man came
    from the prompt never naming his gender."""
    fem = (user_gender or 'male') == 'female'
    lines = ['[USER CONTEXT]',
             f'User Gender: {"Female (Женщина)" if fem else "Male (Мужчина)"}.']
    title = str(user_name or '').strip().replace('\n', ' ')[:60]
    if title:
        lines.append(f'Имя пользователя: {title}.')
    lines.append(f'Твоя задача — обращаться к пользователю строго в '
                 f'{"женском" if fem else "мужском"} роде. Никогда не путай пол пользователя.')
    return '\n'.join(lines)


def roleplay_block(name: str, duo: bool = False) -> str:
    """Блок 2 owner ТЗ: exactly one voice per reply. In a duo chat the model
    legitimately voices both girls and every line starts with a name, so only
    there the signature stays."""
    if duo:
        body = (f'Ты отыгрываешь роль ТОЛЬКО девушек этого чата. Твоя текущая роль: {name}, '
                'основная девушка. Запрещено генерировать реплики за пользователя и за других людей. '
                f'В этом чате две девушки, поэтому каждую свою реплику начинай с имени через двоеточие '
                f'(например «{name}: …») — как описано в инструкции про вторую девушку.')
    else:
        body = (f'Ты отыгрываешь роль ТОЛЬКО ОДНОГО персонажа. Твоя текущая роль: {name}. '
                'Отвечай ТОЛЬКО от своего лица. Запрещено генерировать реплики за пользователя '
                'и за других персонажей. Не пиши своё имя в начале реплики — сразу начинай с текста '
                'или действия, и никогда не ставь перед своей репликой его имя.')
    return '[ROLEPLAY INSTRUCTIONS]\n' + body


def stop_sequences(user_name: str = '') -> list[str]:
    """V3.143.0: cut the generation where she starts typing his line. Only the
    client's name with a colon — the bare name would truncate a normal sentence
    that mentions him, and in a duo chat her own name opens every line."""
    title = str(user_name or '').strip().replace('\n', ' ')[:60]
    stops = ['User:', 'Пользователь:']
    if title:
        stops.append(f'{title}:')
    return stops


@lru_cache(maxsize=8)
def get_character(character_id: str = CHARACTER_ID) -> dict:
    """Load character JSON by id. Falls back to default CHARACTER_FILE if no specific file exists."""
    path = Path(CHARACTER_DIR) / f"{character_id}.json"
    if path.exists() and character_id != CHARACTER_ID:
        return json.loads(path.read_text(encoding="utf-8"))
    with open(CHARACTER_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=1)
def get_anna():
    return get_character(CHARACTER_ID)


