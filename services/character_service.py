import json
from functools import lru_cache
from pathlib import Path
from config import CHARACTER_FILE, CHARACTER_DIR, CHARACTER_ID

@lru_cache(maxsize=8)
def get_character(character_id: str = CHARACTER_ID) -> dict:
    """Load character JSON by id. Falls back to default CHARACTER_FILE if no specific file exists."""
    path = Path(CHARACTER_DIR) / f"{character_id}.json"
    if path.exists() and character_id != CHARACTER_ID:
        return json.loads(path.read_text(encoding="utf-8"))
    with open(CHARACTER_FILE, "r", encoding="utf-8") as f:
        return json.load(f)


@lru_cache(maxsize=1)
def get_anna():
    return get_character(CHARACTER_ID)


def _gendered_terms(character_id: str) -> dict:
    """Return pronouns and labels for a character."""
    from services.character_card_service import get_card
    from services.character_dna_service import get_character_dna
    card = get_card(character_id)
    gender = card.gender if card else 'female'
    dna = get_character_dna(character_id)
    if gender == 'male':
        return {
            'gender_noun': 'парень',
            'gender_noun_en': 'man',
            'partner_noun': 'девушка',
            'self_pronoun': 'он',
            'self_pronoun_cap': 'Он',
            'self_reflexive': 'себя',
            'gender_adj': 'живой парень',
        }
    return {
        'gender_noun': 'девушка',
        'gender_noun_en': 'woman',
        'partner_noun': 'парень',
        'self_pronoun': 'она',
        'self_pronoun_cap': 'Она',
        'self_reflexive': 'себя',
        'gender_adj': 'живая девушка',
    }


